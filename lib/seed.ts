function site(name: string, address: string, city: string, country: string, accessNotes: string): Site {
  return { name, address, city, country, accessNotes };
}

function piece(partial: Piece): Piece {
  return partial;
}

function file(partial: CargoFile): CargoFile {
  return partial;
}

function note(id: string, at: string, author: string, text: string): Note {
  return { id, at, author, text };
}

function ev(id: string, at: string, kind: TimelineEvent["kind"], text: string): TimelineEvent {
  return { id, at, kind, text };
}

function cost(
  id: string,
  layer: Layer,
  description: string,
  vendor: string,
  amount: number,
  lineStatus: LineStatus,
  basis = "lump sum",
  extra = "",
): CostLine {
  return { id, layer, description, vendor, basis, amount, lineStatus, note: extra };
}

